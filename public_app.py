# Release packet identity. The packet is a derivative of the source packet: 84 data files are
# unchanged and the statistics normalization is regenerated by tools/compile_statistics.py.
RELEASE_SNAPSHOT_ID = 'sha256:22642501f4c8829262c5724d3a09ce1f60ed0a0c06792f4e6c0c9b829c8f3a15'
RELEASE_MANIFEST_SHA256 = '889098b40aee4f2ff3ecb814fcaf76bb55b35c770ee3955359953152ce3a609f'
DERIVED_FILES = {'data/statistics/observations.json'}
MANIFEST_FILES = {'PACKET-MANIFEST.json', 'SOURCE-PACKET-MANIFEST.json'}


class RuntimePacket(Packet):
    """Verify runtime data against the pinned release manifest and the pinned source manifest.

    PACKET-MANIFEST.json is this release's manifest with its own snapshot identity.
    SOURCE-PACKET-MANIFEST.json is the unchanged original packet manifest. Every data
    file except the regenerated statistics normalization must equal its source entry.
    Four nonruntime handoff/specification files of the source packet are absent.
    """
    def _verify(self):
        if self.manifest_sha256 != RELEASE_MANIFEST_SHA256 or self.snapshot_id != RELEASE_SNAPSHOT_ID:
            raise PacketError('Runtime packet does not match the pinned release manifest')
        source_path = self.dir / 'SOURCE-PACKET-MANIFEST.json'
        if source_path.is_symlink() or not source_path.is_file():
            raise PacketError('Source packet manifest is missing')
        source_bytes = source_path.read_bytes()
        source = json.loads(source_bytes)
        if hashlib.sha256(source_bytes).hexdigest() != ACCEPTED_MANIFEST_SHA256 or source.get('snapshot_id') != ACCEPTED_SNAPSHOT_ID:
            raise PacketError('Runtime packet does not bind the accepted source manifest')
        original = {f['path']: f for f in source['files'] if f['path'].startswith('data/')}
        runtime = self.manifest['files']
        if {f['path'] for f in runtime} != set(original):
            raise PacketError('Release manifest does not list the source data files')
        lines = []
        for row in sorted(runtime, key=lambda f: f['path'].encode('utf-8')):
            p = self.dir / row['path']
            if p.is_symlink() or not p.is_file() or p.stat().st_size != row['bytes'] or hashlib.sha256(p.read_bytes()).hexdigest() != row['sha256']:
                raise PacketError('Runtime data integrity check failed: ' + row['path'])
            derived = row['path'] in DERIVED_FILES
            if row.get('origin') != ('release_derived' if derived else 'source_packet_unchanged'):
                raise PacketError('Unexpected file origin: ' + row['path'])
            if not derived and (row['bytes'], row['sha256']) != (original[row['path']]['bytes'], original[row['path']]['sha256']):
                raise PacketError('Unchanged file differs from the source packet: ' + row['path'])
            lines.append(f"{row['sha256']}  {row['bytes']}  {row['path']}\n")
        if 'sha256:' + hashlib.sha256(''.join(lines).encode('utf-8')).hexdigest() != self.snapshot_id:
            raise PacketError('snapshot_id does not match the digest rule')
        actual = {str(p.relative_to(self.dir)) for p in self.dir.rglob('*') if p.is_file()}
        if actual != set(original) | MANIFEST_FILES:
            raise PacketError('Unexpected or missing runtime packet files')
        return {'verified': True, 'verification_scope': 'statewide_runtime_data', 'file_count': len(runtime),
                'snapshot_id': self.snapshot_id, 'manifest_sha256': self.manifest_sha256,
                'manifest_sha256_matches_accepted': True,
                'source_snapshot_id': ACCEPTED_SNAPSHOT_ID, 'source_manifest_sha256': ACCEPTED_MANIFEST_SHA256,
                'source_files_unchanged': len(runtime) - len(DERIVED_FILES),
                'release_derived_files': sorted(DERIVED_FILES), 'omitted_nonruntime_files': 4}


class PrivateMetricsService(Service):
    """Record only bounded operational metadata, excluding visitor content."""
    def __init__(self, core, state_dir):
        super().__init__(core, variant='A')
        self.metrics = logging.Logger('haic.metrics')
        sink = RotatingFileHandler(state_dir / 'metrics.jsonl', maxBytes=5*1024*1024, backupCount=2, encoding='utf-8')
        sink.setFormatter(logging.Formatter('%(message)s'))
        self.metrics.addHandler(sink)

    def _log(self, name, record):
        # Rows never state a model-call count: the process also serves language routes, and the protected FundingLedger
        # (plus private operator diagnostics) is the only authority for model calls, Count starts and usage.
        safe = {'ts': int(time.time()), 'variant': 'A', 'model_calls_authority': 'funding_ledger'}
        # Values come from closed service routes/statuses, never arbitrary event detail.
        for key in ('phase', 'status', 'operation', 'core_called', 'elapsed_ms'):
            if key in record:
                safe[key] = record[key]
        if name == 'errors.jsonl':
            safe = {'ts': int(time.time()), 'variant': 'A', 'phase': 'internal_error', 'model_calls_authority': 'funding_ledger'}
        self.metrics.info(json.dumps(safe, sort_keys=True))


def language_service(investigation):
    """Language is off unless the protected operator environment enables it AND names one validated profile.
    The profile is never chosen by a question, cookie or client; an unknown profile fails startup closed."""
    enabled = os.environ.get('HAIC_LANGUAGE_ENABLED') == '1'
    if not enabled:
        return LanguageService(investigation, enabled=False)
    name = os.environ.get('HAIC_LANGUAGE_PROFILE')
    if not name:
        raise ValueError('HAIC_LANGUAGE_ENABLED=1 requires HAIC_LANGUAGE_PROFILE naming a validated profile')
    return LanguageService(investigation, enabled=True, profile=load_profile(name))


def language_view(out):
    plan_proposal = out.get('status') == 'propose' and out.get('intent') in ('create_plan', 'replace_plan')
    if out.get('enabled') is True or plan_proposal:
        return dict(out, message=(
            'A clear, supported proposal can run directly on the bundled data. '
            'The app can require review before a district change, a comparison that needs '
            'a chamber choice, or a change that affects earlier work.'))
    return out


def load_core(input_profile=None, r2_input_dir=None):
    profile = input_profile or os.environ.get('HAIC_INPUT_PROFILE', 'public')
    if profile == 'public':
        from districtbrief.public_packet import PublicPacket, public_metadata
        packet = PublicPacket(ROOT / 'runtime-packet')
        metadata = public_metadata(ROOT / 'candidate-metadata')
    elif profile == 'r2':
        supplied = r2_input_dir or os.environ.get('HAIC_R2_INPUT_DIR')
        if not supplied or not Path(supplied).is_absolute():
            raise ValueError('The r2 profile requires an absolute HAIC_R2_INPUT_DIR with complete retained R2 inputs')
        retained = Path(supplied)
        packet = RuntimePacket(retained / 'runtime-packet')
        from districtbrief.candidate_metadata import CandidateMetadata
        metadata = CandidateMetadata(retained / 'candidate-metadata')
    else:
        raise ValueError('HAIC_INPUT_PROFILE must be public or r2')
    return Core(packet, metadata=metadata)


CATALOG_PAGE_FIELDS = frozenset({'offset', 'limit', 'geography_id', 'metric_id', 'q', 'snapshot_id'})
CATALOG_PAGE_MAX = 100


def catalog_fold(text):
    """Search folding: case, diacritics and the ʻokina/apostrophes are ignored (Hawaiʻi matches Hawaii)."""
    decomposed = unicodedata.normalize('NFKD', str(text))
    plain = ''.join(c for c in decomposed if not unicodedata.combining(c) and c not in "\u02bb\u2018\u2019'`")
    return ' '.join(plain.casefold().split())


def catalog_row_text(o, geos, metrics):
    """The words a catalog row shows: geography, measure, published estimate and MOE, unit and universe.
    The publisher's ***** MOE marker also matches its on-screen wording, Not published."""
    moe = o['moe_display'] or ''
    return ' '.join((geos[o['geography_id']], metrics[o['metric_id']]['label'], o['estimate_display'] or '', moe,
                     'Not published' if moe == '*****' else '', o['unit'] or '', metrics[o['metric_id']].get('universe') or ''))


class Application:
    def __init__(self, state_dir, *, secure_cookie=True, input_profile=None, r2_input_dir=None):
        state_dir = Path(state_dir)
        if not state_dir.is_absolute():
            raise ValueError('HAIC_STATE_DIR must be an absolute writable directory')
        state_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
        self.service = PrivateMetricsService(load_core(input_profile, r2_input_dir), state_dir)
        self.investigation = Investigation(self.service.core)
        self.language = language_service(self.investigation)
        self.investigation_sessions = {}
        self.secret = secrets.token_bytes(32)
        self.secure_cookie = secure_cookie
        self._catalog_index = None
        # Development HTTP uses a separate cookie name. Production always uses __Host-.
        self.cookie_name = COOKIE_NAME if secure_cookie else 'haic_session_local'

    def session(self, environ):
        try:
            # A malformed unrelated domain cookie must not hide our exact name.
            # Duplicate named cookies fail closed instead of choosing an order.
            values = []
            for pair in environ.get('HTTP_COOKIE', '').split(';'):
                name, sep, value = pair.strip().partition('=')
                if name.strip() == self.cookie_name:
                    values.append(value if sep else '')
            if len(values) != 1:
                raise ValueError('missing or duplicate session')
            token = values[0]
            if not re.fullmatch(r'[0-9]{1,10}\.[0-9a-f]{64}\.[0-9a-f]{64}', token, flags=re.ASCII):
                raise ValueError('invalid session token')
            stamp, random, signature = token.split('.')
            signed = stamp + '.' + random
            age = int(time.time()) - int(stamp)
            expected = hmac.new(self.secret, signed.encode('ascii'), hashlib.sha256).hexdigest()
            if not 0 <= age <= COOKIE_AGE or not hmac.compare_digest(signature, expected):
                raise ValueError('expired or invalid session')
            return hashlib.sha256(token.encode('ascii')).hexdigest(), None
        except (ValueError, UnicodeError):
            signed = str(int(time.time())) + '.' + secrets.token_hex(32)
            token = signed + '.' + hmac.new(self.secret, signed.encode('ascii'), hashlib.sha256).hexdigest()
            cookie = f'{self.cookie_name}={token}; Path=/; HttpOnly; SameSite=Strict; Max-Age={COOKIE_AGE}'
            if self.secure_cookie:
                cookie += '; Secure'
            return hashlib.sha256(token.encode('ascii')).hexdigest(), cookie

    def catalog_page(self, query_string):
        """One page of the statistics catalog. Filters and search apply to every observation before paging,
        in the catalog's own stable order. Read-only and value-free beyond the catalog itself."""
        cat = self.service.catalog()
        if self._catalog_index is None:
            geos = {g['geography_id']: g['label'] for g in cat['geographies']}
            metrics = {m['metric_id']: m for m in cat['metrics']}
            self._catalog_index = [(o, catalog_fold(catalog_row_text(o, geos, metrics))) for o in cat['observations']]
        q = parse_qs(query_string, max_num_fields=len(CATALOG_PAGE_FIELDS), keep_blank_values=True, strict_parsing=bool(query_string))
        if not set(q) <= CATALOG_PAGE_FIELDS or any(len(v) != 1 for v in q.values()):
            raise ValueError('Use only offset, limit, geography_id, metric_id, q and snapshot_id, each at most once.')
        one = {k: v[0] for k, v in q.items()}
        if 'snapshot_id' in one and one['snapshot_id'] != self.service.snapshot_id:
            return 409, self.error('The data snapshot changed. Reload the page to see the current catalog.')
        offset, limit = one.get('offset', '0'), one.get('limit', str(render.CATALOG_PAGE_SIZE))
        if not re.fullmatch(r'[0-9]{1,6}', offset, flags=re.ASCII) or not re.fullmatch(r'[0-9]{1,3}', limit, flags=re.ASCII):
            raise ValueError('offset and limit must be whole numbers.')
        offset, limit = int(offset), int(limit)
        if not 1 <= limit <= CATALOG_PAGE_MAX:
            raise ValueError(f'limit must be 1 to {CATALOG_PAGE_MAX}.')
        geo, metric, text = one.get('geography_id', ''), one.get('metric_id', ''), one.get('q', '')
        if geo and geo not in {g['geography_id'] for g in cat['geographies']}:
            raise ValueError('Unknown geography_id.')
        if metric and metric not in {m['metric_id'] for m in cat['metrics']}:
            raise ValueError('Unknown metric_id.')
        if len(text) > render.CATALOG_QUERY_MAX:
            raise ValueError(f'Search text is limited to {render.CATALOG_QUERY_MAX} characters.')
        words = catalog_fold(text).split()
        matched = [o for o, hay in self._catalog_index
                   if (not geo or o['geography_id'] == geo) and (not metric or o['metric_id'] == metric)
                   and all(w in hay for w in words)]
        if offset and offset >= len(matched):
            raise ValueError('offset is beyond the last matching row.')
        page = matched[offset:offset + limit]
        return 200, {'status': 'ok', 'snapshot_id': self.service.snapshot_id, 'total': len(self._catalog_index),
                     'matched': len(matched), 'offset': offset, 'limit': limit,
                     'filters': {'geography_id': geo, 'metric_id': metric, 'q': text},
                     'finding_ids': [o['finding_id'] for o in page], 'rows_html': render.catalog_rows_html(cat, page),
                     'model_calls': 0}

    @staticmethod
    def error(reason):
        return {'status': 'error', 'reason': reason, 'model_calls': 0}

    @staticmethod
    def route_error(path, reason):
        if path == '/api/investigation':
            return InvestigationError(400,'request_rejected',reason,retry_action='correct_request_or_retry').envelope()
        return Application.error(reason)

    def __call__(self, environ, start_response):
        method, path = environ.get('REQUEST_METHOD', ''), environ.get('PATH_INFO', '')
        extra = []
        try:
            code, content_type, body = self.dispatch(environ, extra)
        except Exception:
            self.service._log('errors.jsonl', {})
            code, content_type, body = 500, 'application/json; charset=utf-8', self.route_error(path, 'The request failed. Previous results remain in this browser. Please run again.')
        if not isinstance(body, bytes):
            body = json.dumps(body, ensure_ascii=False, separators=(',',':'), allow_nan=False).encode('utf-8')
        status = {200:'OK',202:'Accepted',204:'No Content',400:'Bad Request',403:'Forbidden',404:'Not Found',405:'Method Not Allowed',409:'Conflict',411:'Length Required',413:'Content Too Large',415:'Unsupported Media Type',429:'Too Many Requests',503:'Service Unavailable',500:'Internal Server Error'}[code]
        start_response(f'{code} {status}', [('Content-Type',content_type),('Content-Length',str(len(body))), *HEADERS, *extra])
        return [b'' if method == 'HEAD' else body]

    def dispatch(self, environ, extra):
        method, path = environ.get('REQUEST_METHOD', ''), environ.get('PATH_INFO', '')
        ct = 'application/json; charset=utf-8'
        if method not in ('GET', 'HEAD', 'POST'):
            extra.append(('Allow', 'GET, HEAD, POST'))
            return 405, ct, self.route_error(path, 'Method not allowed.')
        if len(path) > 2048 or len(environ.get('QUERY_STRING', '')) > 2048:
            return 400, ct, self.route_error(path, 'Request target is too long.')
        if method in ('GET', 'HEAD'):
            if path in ('/api/health', '/healthz'):
                return 200, ct, {'status':'ok', 'snapshot_id':self.service.snapshot_id, 'packet':self.service.core.packet.verification, 'runtime':self.service.identity(), 'investigation':self.investigation.bootstrap(), 'language':language_view(self.language.bootstrap()), 'language_profile':self.language.identity(), 'model_calls':0}
            if path in ('/', '/index.html'):
                _, cookie = self.session(environ)
                if cookie: extra.append(('Set-Cookie',cookie))
                return 200, 'text/html; charset=utf-8', (ROOT / 'static/index.html').read_bytes()
            if path == '/favicon.ico': return 204, 'image/x-icon', b''
            if path.startswith('/static/') and path[8:] in STATIC:
                name = path[8:]
                return 200, ('application/javascript' if name.endswith('.js') else 'text/css') + '; charset=utf-8', (ROOT / 'static' / name).read_bytes()
            if path == '/api/catalog':
                _, cookie = self.session(environ)
                if cookie: extra.append(('Set-Cookie',cookie))
                out = dict(self.service.catalog())
                out['investigation'] = self.investigation.bootstrap()
                out['language'] = language_view(self.language.bootstrap())
                return 200, ct, out
            if path == '/api/catalog/observations':
                try:
                    code, out = self.catalog_page(environ.get('QUERY_STRING', ''))
                except ValueError as exc:
                    reason = str(exc) if str(exc).endswith('.') and len(str(exc)) < 120 else 'The catalog page request is malformed.'
                    return 400, ct, self.route_error(path, reason)
                return code, ct, out
            if path == '/api/geometry':
                try:
                    q = parse_qs(environ.get('QUERY_STRING',''), max_num_fields=4, keep_blank_values=True, strict_parsing=True)
                    if set(q) != {'snapshot_id','chamber','code','session'} or any(len(v)!=1 for v in q.values()):
                        raise ValueError('invalid fields')
                    if not re.fullmatch(r'sha256:[0-9a-f]{64}',q['snapshot_id'][0]) or q['chamber'][0] not in ('house','senate') or not re.fullmatch(r'[0-9]{3}',q['code'][0],flags=re.ASCII):raise ValueError('malformed identity')
                    if q['snapshot_id'][0] != self.investigation.snapshot_id:
                        return 409, ct, InvestigationError(409,'snapshot_unavailable','The geometry snapshot is not admitted.').envelope()
                    if q['session'][0] not in ('2024','2026'):raise ValueError('invalid session')
                    out=geometry_payload(self.service.core.packet,self.investigation.snapshot_id,q['chamber'][0],q['code'][0],int(q['session'][0]))
                    out['indicator'] = indicator_payload(self.service.core, self.investigation.snapshot_id, q['chamber'][0], q['code'][0], int(q['session'][0]))
                    return 200, ct, out
                except ValueError:
                    return 400, ct, self.route_error(path, 'Geometry requires exactly snapshot_id, chamber, code and session with admitted values.')
                except KeyError:
                    return 404, ct, self.route_error(path, 'Geometry is unavailable for this identity.')
            if path == '/api/source':
                try:
                    q = parse_qs(environ.get('QUERY_STRING',''), max_num_fields=4)
                except ValueError:
                    return 400, ct, self.route_error(path, 'Source query accepts at most four fields.')
                out = self.service.source((q.get('source_id') or [None])[0], (q.get('finding_id') or [None])[0])
                return 200 if out['status']=='ok' else 404 if out['status']=='unsupported' else 400, ct, out
            return 404, ct, self.route_error(path, 'Not found.')
        if path not in ('/api/resolve','/api/execute','/api/event','/api/investigation','/api/language/start','/api/language/status','/api/language/cancel'):
            return 404, ct, self.route_error(path, 'Not found.')
        session, cookie = self.session(environ)
        if cookie:
            extra.append(('Set-Cookie',cookie))
            return 403, ct, self.route_error(path, 'Your session was refreshed. Press Run again; your selections are kept.')
        # Browsers mark cross-site requests. SameSite cookies and exact Origin/Host checks
        # also protect browsers without Fetch Metadata. No proxy-forwarded host is trusted.
        origin = environ.get('HTTP_ORIGIN')
        host = environ.get('HTTP_HOST', '')
        if environ.get('HTTP_SEC_FETCH_SITE') == 'cross-site' or (origin and origin not in ('https://' + host, 'http://' + host if not self.secure_cookie else 'https://' + host)):
            return 403, ct, self.route_error(path, 'Cross-origin requests are not accepted.')
        if environ.get('CONTENT_TYPE','').split(';',1)[0].strip().lower() != 'application/json':
            return 415, ct, self.route_error(path, 'Content-Type must be application/json.')
        try: length = int(environ.get('CONTENT_LENGTH',''))
        except ValueError: return 411, ct, self.route_error(path, 'Content-Length is required.')
        if not 0 < length <= MAX_BODY:
            return 413 if length > MAX_BODY else 400, ct, self.route_error(path, 'Body must be 1–65536 bytes of JSON.')
        raw = environ['wsgi.input'].read(length)
        try:
            if len(raw) != length: raise ValueError('incomplete body')
            def pairs(items):
                out = {}
                for key,value in items:
                    if key in out: raise ValueError('duplicate key')
                    out[key] = value
                return out
            body = json.loads(raw.decode('utf-8'), object_pairs_hook=pairs, parse_constant=lambda _: (_ for _ in ()).throw(ValueError('nonfinite')))
            json.dumps(body,ensure_ascii=False,allow_nan=False).encode('utf-8')
        except (ValueError, RecursionError):
            return 400, ct, self.route_error(path, 'Body is not valid UTF-8 JSON.')
        if not isinstance(body,dict): return 400, ct, self.route_error(path, 'Body must be a JSON object.')
        if path.startswith('/api/language/'):
            code, out = self.language.handle(path.rsplit('/', 1)[1], body, session)
            return code, ct, language_view(out)
        if path == '/api/event':
            body['session_id'] = session
            out = self.service.event(body)
            return 200 if out['status']=='ok' else 400, ct, out
        if path == '/api/investigation':
            rid=body.get('request_id')
            try:
                # A bounded correlation registry binds client request IDs to the issuing session.
                # Stateless plan contents/results are never retained here.
                known=self.investigation_sessions.get(rid) if isinstance(rid,str) else None
                if known is not None and known != session:
                    raise InvestigationError(403,'session_mismatch','Use a fresh request ID in this session.','request_id','retry_new_request')
                out=self.investigation.handle(body)
                if len(self.investigation_sessions)>=1024:self.investigation_sessions.pop(next(iter(self.investigation_sessions)))
                self.investigation_sessions[rid]=session
                return 200, ct, out
            except InvestigationError as exc:
                return exc.status, ct, exc.envelope(body)
        rid = body.get('request_id')
        if not isinstance(rid,str) or not re.fullmatch(r'[A-Za-z0-9._:-]{1,80}',rid):
            return 400, ct, self.route_error(path, 'A valid request_id is required.')
        internal = 'web_' + hashlib.sha256((session + ':' + rid).encode('ascii')).hexdigest()
        body['request_id'] = internal
        if path == '/api/resolve':
            action = body.get('action')
            if action is not None and not isinstance(action,dict):
                return 400, ct, self.route_error(path, 'action must be an object.')
            body['action'] = dict(action or {'kind':'run'}, session_id=session)
            # Reusing a pending ID must not overwrite an admitted request.
            if internal in self.service.pending:
                return 409, ct, self.route_error(path, 'This request_id is already waiting. Submit a new request_id.')
            out = self.service.resolve(body)
        else:
            out = self.service.execute(body)
        # Internal request IDs remain cookie-bound. Keep the browser protocol's original ID.
        out['request_id'] = rid
        if out.get('header_html'): out['header_html'] = out['header_html'].replace(internal,rid)
        return 400 if out.get('validation_errors') else 200, ct, out


def create_application():
    state = os.environ.get('HAIC_STATE_DIR')
    if not state:
        raise RuntimeError('Set HAIC_STATE_DIR to an absolute writable directory outside the release')
    return Application(state, secure_cookie=os.environ.get('HAIC_LOCAL_HTTP') != '1')
